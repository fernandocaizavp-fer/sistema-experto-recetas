# --- MOTOR DE INFERENCIA ---
def motor_de_inferencia(hechos, reglas):
    receta_final = None
    nuevos = True

    while nuevos:
        nuevos = False
        for regla in reglas:
            if all(hechos.get(clave) == valor for clave, valor in regla["si"]):
                clave_conclusion, valor_conclusion = regla["entonces"]
                if hechos.get(clave_conclusion) != valor_conclusion:
                    hechos[clave_conclusion] = valor_conclusion
                    nuevos = True
                    if clave_conclusion == "receta":
                        receta_final = valor_conclusion
    return receta_final

# --- FUNCIÓN PARA GRADIO ---
def recomendar_plato(pasta, verduras, carne, pescado, huevo, lacteos, legumbres, vegano, sin_gluten, rapido):
    hechos = {
        "tiene_pasta": "si" if pasta else "no",
        "tiene_verduras": "si" if verduras else "no",
        "tiene_carne": "si" if carne else "no",
        "tiene_pescado": "si" if pescado else "no",
        "tiene_huevo": "si" if huevo else "no",
        "tiene_lacteos": "si" if lacteos else "no",
        "tiene_legumbres": "si" if legumbres else "no",
        "prefiere_vegano": "si" if vegano else "no",
        "prefiere_sin_gluten": "si" if sin_gluten else "no",
        "prefiere_plato_rapido": "si" if rapido else "no"
    }

    resultado = motor_de_inferencia(hechos, reglas)

    if resultado:
        return f"✨ **Plato Recomendado:**\n\n# {resultado}\n\n¡Que aproveche! 🍽️"
    else:
        return "❌ **No se encontró una receta** con los ingredientes y preferencias seleccionados.\n\nIntenta con otra combinación."

